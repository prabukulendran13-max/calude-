#!/usr/bin/env python3
"""Build the installable app from game.html.

game.html is the page body as published on claude.ai. This writes:
  index.html  the full page, with app metadata, the bundled font and the offline worker
  sw.js       the offline worker, whose cache name changes whenever any app file changes
Run it after every edit to game.html:  python3 carrom-duel/build.py
"""
import hashlib, json, pathlib, re

root = pathlib.Path(__file__).resolve().parent
src = (root / 'game.html').read_text()
head, body = src.split('<div id="app">', 1)
head = re.sub(r'<link rel="preconnect"[^>]*>\n|<link href="https://fonts\.googleapis\.com[^>]*>\n', '', head)
assert 'fonts.googleapis' not in head, 'font link not removed'

APP_HEAD = '''<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">
<meta name="description" content="Carrom vs the bot. Pot 'em all. Works offline.">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="Carrom Duel">
<meta name="application-name" content="Carrom Duel">
<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="app/icon-180.png">
<link rel="icon" type="image/png" sizes="32x32" href="app/icon-32.png">
<style>@font-face{font-family:"Baloo 2";font-style:normal;font-weight:400 800;font-display:swap;src:url(app/baloo2-latin.woff2) format("woff2")}@font-face{font-family:"Lilita One";font-style:normal;font-weight:400;font-display:swap;src:url(app/lilita-one-latin.woff2) format("woff2")}</style>
'''
REGISTER = '''<script>
if('serviceWorker' in navigator&&/^https?:$/.test(location.protocol))addEventListener('load',()=>navigator.serviceWorker.register('sw.js',{updateViaCache:'none'}).catch(()=>{}));
</script>
'''
SW_TEMPLATE = '''// Generated by build.py. Keeps every app file on the device so the game opens with no connection.
// The page itself is fetched fresh whenever the device is online, so a launch always shows the newest
// version; the saved copy is only used offline. Each new version announces itself so open copies refresh.
const VERSION='__VERSION__',CACHE='carrom-duel-'+VERSION;
const ASSETS=__ASSETS__;
self.addEventListener('install',e=>{e.waitUntil(caches.open(CACHE).then(c=>c.addAll(ASSETS.map(u=>new Request(u,{cache:'reload'})))).then(()=>self.skipWaiting()))});
self.addEventListener('activate',e=>{e.waitUntil((async()=>{
  const ks=await caches.keys();
  await Promise.all(ks.filter(k=>k.startsWith('carrom-duel-')&&k!==CACHE).map(k=>caches.delete(k)));
  await self.clients.claim();
  for(const c of await self.clients.matchAll({type:'window'}))c.postMessage({type:'carrom-duel-version',version:VERSION});
})())});
self.addEventListener('fetch',e=>{
  const r=e.request,u=new URL(r.url);
  if(r.method!=='GET'||u.origin!==location.origin)return;
  if(r.mode==='navigate'||u.pathname.endsWith('/')||u.pathname.endsWith('/index.html')){
    e.respondWith((async()=>{
      const c=await caches.open(CACHE);
      try{
        const res=await Promise.race([fetch(r.url,{cache:'no-store',credentials:'same-origin'}),new Promise((_,no)=>setTimeout(no,4000))]);
        if(res&&res.ok){c.put('index.html',res.clone());return res}
      }catch(_){}
      return (await c.match('index.html'))||(await c.match('./'))||Response.error();
    })());
    return;
  }
  e.respondWith(caches.open(CACHE).then(async c=>{
    const hit=await c.match(r,{ignoreSearch:true});
    const net=fetch(r,{cache:'no-cache'}).then(res=>{if(res&&res.ok)c.put(r,res.clone());return res}).catch(()=>null);
    if(hit){e.waitUntil(net);return hit}
    return (await net)||Response.error();
  }));
});
'''

ASSETS = ['index.html', 'manifest.webmanifest', 'app/baloo2-latin.woff2', 'app/lilita-one-latin.woff2', 'app/icon-32.png',
          'app/icon-180.png', 'app/icon-192.png', 'app/icon-512.png', 'app/icon-maskable-512.png']
digest = hashlib.sha256((src + APP_HEAD + REGISTER + SW_TEMPLATE).encode())
for a in ASSETS[1:]:
    digest.update((root / a).read_bytes())
version = digest.hexdigest()[:8]

(root / 'index.html').write_text(
    f'<!doctype html>\n<html lang="en">\n<head>\n{APP_HEAD}<script>window.APP_BUILD="{version}"</script>\n{head.strip()}\n</head>\n<body>\n'
    f'<div id="app">{body.rstrip()}\n{REGISTER}</body>\n</html>\n')

(root / 'sw.js').write_text(SW_TEMPLATE.replace('__VERSION__', version).replace('__ASSETS__', json.dumps(['./'] + ASSETS)))
print('built index.html and sw.js, cache version', version)
